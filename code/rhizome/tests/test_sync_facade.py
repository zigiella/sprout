        self.assertTrue(summary["gemma_narrator"]["used"])
        self.assertEqual(summary["counts"]["total"], 2)
        self.assertEqual(summary["headline"], "Gemma visit headline")
        self.assertIn("Gemma rewrote", summary["summary"])

