def _stop_server(server) -> None:
    server.shutdown()
    server.server_close()


def _get_json(base_url: str, path: str):
    with urllib.request.urlopen(f"{base_url}{path}", timeout=3) as response:
        assert response.headers["Content-Type"].startswith("application/json")
        return json.loads(response.read().decode("utf-8"))


def _get_json_from_file(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def _post_json(base_url: str, path: str, payload):
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        f"{base_url}{path}",
        data=body,
        method="POST",
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=3) as response:
        assert response.headers["Content-Type"].startswith("application/json")
        return json.loads(response.read().decode("utf-8"))


def _run_server(
    data_dir: Path,
    node_id: str = "rhizome_01",
    state_dir: Path | None = None,
    narrator_url: str | None = None,
):
    server = make_server(
        "127.0.0.1",
        0,
        data_dir,
        node_id=node_id,
        state_dir=state_dir,
        narrator_url=narrator_url,
        narrator_model="fake-gemma",
    )
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    host, port = server.server_address
    return server, f"http://{host}:{port}"


def _run_fake_adapter(content: str):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format: str, *args: object) -> None:
            return

        def do_POST(self) -> None:
            content_length = int(self.headers.get("Content-Length", "0"))
            if content_length:
                self.rfile.read(content_length)
            body = json.dumps({"message": {"content": content}}).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    host, port = server.server_address
    return server, f"http://{host}:{port}"


def _policy_packet(target_node_id: str = "rhizome_01") -> dict:
    created_at = datetime.now(timezone.utc).replace(microsecond=0)
    valid_until = created_at + timedelta(hours=12)
    created = created_at.strftime("%Y-%m-%dT%H:%M:%SZ")
    valid = valid_until.strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "schema_version": "1.0",
        "created_at": created,
        "origin_node_id": "pollen_01",
        "signature": None,
        "policy_id": f"pkt_{target_node_id}_pollen_visit_test",
        "target_node_id": target_node_id,
        "valid_until": valid,
        "version_chain": ["pkt_seed", f"pkt_{target_node_id}_pollen_visit_test"],
        "mode_default": "conservative",
        "policy_origin": "pollen-visit",
        "policy_scope": "transient",
        "rules": {
            "watering_window": {
                "start_hour_local": 6,
                "end_hour_local": 9,
            },
            "soil_moisture_thresholds": {
                "parcel_a": {
                    "min_pct": 35.0,
                    "target_pct": 50.0,
                }
            },
            "max_watering_duration_s": 30,
            "daily_water_budget_liters": 4.0,
            "tank_minimum_pct": 20.0,
            "require_vision_confirmation": False,
            "conservative_triggers": ["pollen_visit_voice_policy"],
        },
        "rationale": "Policy generated by Pollen Mini-Evaluator test.",
        "notes": "transient voice-to-policy test",
    }


class SyncFacadeTest(unittest.TestCase):
    def test_pollen_read_endpoints_return_contract_shapes(self):
        server, base_url = _run_server(default_data_dir())
        try:
            status = _get_json(base_url, "/status")
            snapshot = _get_json(base_url, "/snapshot/latest")
            receipts = _get_json(base_url, "/receipts")
            explanation = _get_json(base_url, f"/explain/decision/{receipts[0]['decision_id']}")
        finally:
            _stop_server(server)

        self.assertEqual(status["status"], "ready")
        self.assertEqual(status["mode"], "read_only_facade")
        self.assertEqual(status["node_id"], "rhizome_01")
        self.assertTrue(snapshot["snapshot_id"])
        self.assertGreaterEqual(snapshot["sensors"]["tank_level_pct"], 0)
        self.assertIsInstance(receipts, list)
        self.assertTrue(receipts[0]["decision_id"])
        self.assertEqual(explanation["source"], "deterministic_receipt_explainer")
        self.assertIn(receipts[0]["action"], explanation["explanation"])

    def test_explanation_can_be_localized_to_english(self):
        server, base_url = _run_server(default_data_dir())
        try:
            receipts = _get_json(base_url, "/receipts")
            explanation = _get_json(
                base_url,
                f"/explain/decision/{receipts[0]['decision_id']}?locale=en",
            )
        finally:
            _stop_server(server)

        self.assertEqual(explanation["locale"], "en")
        self.assertIn("Rhizome executed", explanation["explanation"])

    def test_explanation_respects_not_executed_water_candidate(self):
        with tempfile.TemporaryDirectory() as tmp:
            data_dir = Path(tmp)
            shutil.copy(default_data_dir() / "rhizome_snapshot.json", data_dir / "rhizome_snapshot.json")
            receipt = _get_json_from_file(default_data_dir() / "decision_receipt.json")
            receipt["decision_id"] = "rec_observe_mode"
            receipt["executed"] = False
            receipt["execution_details"] = None
            receipt["blocked_reason"] = "OBSERVE_MODE_EXECUTE_WATER_FALSE"
            (data_dir / "decision_receipt.json").write_text(json.dumps(receipt), encoding="utf-8")
            server, base_url = _run_server(data_dir)
            try:
                explanation = _get_json(base_url, "/explain/decision/rec_observe_mode?locale=en")
            finally:
                _stop_server(server)

        self.assertIn("proposed WATER_A", explanation["explanation"])
        self.assertIn("did not execute", explanation["explanation"])
        self.assertNotIn("executed WATER_A", explanation["explanation"])

